#!/usr/bin/env python3
"""Measures torch.topk on the same GPU as an external baseline; it can also measure DeepSelect and
FlashInfer (named in --impls; they have to be installed first).

Following the list of calls printed by the benchmark driver (build/bench_topk --plan), it generates data
of the same shape and distribution for every call and times it. The columns of the log are those of
bench_topk, so the two can be put side by side when plotting.

Usage (from src/):
  build/bench_topk --plan > build/plan.csv
  python3 bench/bench_torch.py --plan build/plan.csv --reps 5 --out logs/xxx.csv

Differences from bench_topk:
  - the data is generated by torch on the GPU: the same distribution, but not bit-for-bit the same data;
  - torch.topk has no notion of a valid length, so the positions beyond it are first filled with
    negative infinity (untimed);
  - the result of torch.topk is not deterministic, so there is no output hash and the out_hash column is -.

What can be measured (--impls, comma-separated; the default is the first):
  torch_topk_sorted  torch.topk(x, k, sorted=True): selects and then orders by score from high to low,
                     its default usage;
  torch_topk      torch.topk(x, k, sorted=False): selects without ordering, the most favourable for it;
  torch_topk_pos  additionally sorts the positions in ascending order, the output order of this project
                  (which tied position is selected remains non-deterministic);
  deepselect      the fp32 top-k of DeepSelect (deepseek-ai/DeepSelect), given the valid length (end),
                  positions only and unordered, the most favourable for it;
  deepselect_pos  the same with positions in ascending order, the output order of this project;
  flashinfer      the deterministic top-k of FlashInfer (flashinfer-ai/flashinfer):
                  top_k_ragged_transform(x, offsets=0, lengths, k, deterministic=True, tie_break=1).
                  Of its entry points this is the one that takes the valid length; it returns int32
                  positions padded with -1 and no values, the most favourable for it. tie_break=1 asks
                  for ties to go to the smaller position, which needs 128 KB of shared memory per SM;
                  on a GPU with less, pass --flashinfer-tie-break 0 (only to rehearse the script).
When measuring DeepSelect or FlashInfer four more things are checked, one # check line per call:
  - whether the selected set is right (every key above the k-th is selected, nothing is selected twice
    and the count is right);
  - whether ties go to the smaller position (the convention of this project; DeepSelect does not
    promise it, FlashInfer does with tie_break=1);
  - whether repeated runs on the same input give bit-identical output;
  - whether the output is already in ascending position order with the -1 padding at the end (the
    output order of this project; deepselect does not ask for it, the documentation of FlashInfer does
    not promise it).
"""
