def make_scores(call, gen, device):
    rows, width = int(call["rows"]), int(call["width"])
    dist = call["dist"]
    if dist == "normal":
        x = torch.randn(rows, width, generator=gen, device=device)
    elif dist == "narrow":  # [1, 1.25)
        x = torch.rand(rows, width, generator=gen, device=device) * 0.25 + 1.0
    elif dist == "ties":  # the integers 0 to 15
        x = torch.randint(0, 16, (rows, width), generator=gen, device=device).float()
    elif dist in ("gumbel", "logistic"):  # every row takes a random (mu, beta) from the table, see bench/workload.h
        table = torch.tensor(GUMBEL_PARAMS if dist == "gumbel" else LOGISTIC_PARAMS, dtype=torch.float64, device=device)
        pick = table[torch.randint(0, len(table), (rows,), generator=gen, device=device)]
        u = torch.rand(rows, width, generator=gen, device=device, dtype=torch.float64).clamp_(1e-15, 1 - 1e-15)
        t = -torch.log(-torch.log(u)) if dist == "gumbel" else torch.log(u / (1 - u))
        x = (pick[:, :1] + pick[:, 1:] * t).float()
        del u, t
    else:
        raise ValueError(f"unknown distribution {dist}")
    lens = int(call["len_first"]) + int(call["len_step"]) * torch.arange(rows, device=device)
    x.masked_fill_(torch.arange(width, device=device)[None, :] >= lens[:, None], float("-inf"))
    return x, lens.to(torch.int32)


def topk_sorted(x, lens, k):
    return torch.topk(x, k, dim=1, sorted=True).indices


def topk_only(x, lens, k):
    return torch.topk(x, k, dim=1, sorted=False).indices


def topk_pos(x, lens, k):
    return torch.topk(x, k, dim=1, sorted=False).indices.sort(dim=1).values


def deepselect(sorted_index):
    def run(x, lens, k):
        import deep_select  # imported on demand: torch.topk can be measured without DeepSelect installed

        return deep_select.topk(x, k, end=lens, indices_type=torch.int32, sorted_index=sorted_index,
                                return_value=False, idx_oob_fill_value=-1)[1]
    return run


FLASHINFER_TIE_BREAK = 1  # set from --flashinfer-tie-break
_zero_offsets = {}        # rows -> an all-zero int32 tensor, so that allocating it is not timed on every call


def flashinfer_ragged(x, lens, k):
    import flashinfer  # imported on demand, like deep_select

    rows = x.shape[0]
    offsets = _zero_offsets.get(rows)
    if offsets is None:
        offsets = _zero_offsets[rows] = torch.zeros(rows, dtype=torch.int32, device=x.device)
    return flashinfer.top_k_ragged_transform(x, offsets, lens, k, deterministic=True,
                                             tie_break=FLASHINFER_TIE_BREAK)


IMPLS = {
    "torch_topk_sorted": topk_sorted,
    "torch_topk": topk_only,
    "torch_topk_pos": topk_pos,
    "deepselect": deepselect(False),
    "deepselect_pos": deepselect(True),
    "flashinfer": flashinfer_ragged,
}
CHECKED = ("deepselect", "deepselect_pos", "flashinfer")  # deterministic ones: their output is checked
PAD = 2**31 - 1  # stands in for the -1 padding while sorting, so that it goes to the end


def ascending(out):
    """Sorts every row of out (positions, padded with -1) into ascending order with the padding at the end.

    Returns (the sorted output, rows that were not in this order already).
    """
    padded = torch.where(out < 0, torch.full_like(out, PAD), out)
    ordered = padded.sort(dim=1).values
    moved = int((ordered != padded).any(dim=1).sum())
    return torch.where(ordered == PAD, torch.full_like(ordered, -1), ordered), moved


def check_rule(x, lens, k, out):
    """out is the output in ascending position order (padded with -1 at the end).

    Returns (rows with a wrong set, rows with the right set where a tie did not go to the smaller position).
    """
    out = out.long()
    rows = x.shape[0]
    short = lens <= k
    wrong = torch.zeros(rows, dtype=torch.bool, device=x.device)
    # Rows with valid length at most k: should be 0, 1, ..., len - 1 followed by -1 padding
    col = torch.arange(k, device=x.device)[None, :]
    want_short = torch.where(col < lens[:, None], col, torch.full_like(col, -1))
    wrong |= short & (out != want_short).any(dim=1)
    # Other rows: tau is the k-th value; everything above tau is selected, and of those equal to tau the
    # smallest positions are taken
    tau = torch.topk(x, k, dim=1, sorted=False).values.min(dim=1).values
    valid = out >= 0
    vals = x.gather(1, out.clamp(min=0))
    n_gt = (x > tau[:, None]).sum(dim=1)
    twice = (valid[:, 1:] & (out[:, 1:] == out[:, :-1])).any(dim=1)
    bad_set = ((~valid).any(dim=1) | twice | (vals < tau[:, None]).any(dim=1)
               | ((vals > tau[:, None]).sum(dim=1) != n_gt))
    wrong |= ~short & bad_set
    eq = x == tau[:, None]
    quota = k - n_gt
    want_eq = eq & (eq.cumsum(dim=1, dtype=torch.int32) <= quota[:, None])
    got_eq = torch.zeros_like(eq)
    got_eq.scatter_(1, out.clamp(min=0), vals == tau[:, None])
    tie = ~short & ~bad_set & (got_eq != want_eq).any(dim=1)
    return int(wrong.sum()), int(tie.sum())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True)
    ap.add_argument("--reps", type=int, default=5)
    ap.add_argument("--seed", type=int, default=20261111)
    ap.add_argument("--out", required=True)
    ap.add_argument("--impls", default="torch_topk_sorted")
    ap.add_argument("--flashinfer-tie-break", type=int, default=1, choices=(0, 1),
                    help="tie_break passed to FlashInfer; 0 only on a GPU where 1 is not supported")
    args = ap.parse_args()
    global FLASHINFER_TIE_BREAK
    FLASHINFER_TIE_BREAK = args.flashinfer_tie_break
    impls = [(name, IMPLS[name]) for name in args.impls.split(",")]

    with open(args.plan, encoding="utf-8") as f:
        plan = list(csv.DictReader(f))
    device = torch.device("cuda")
    gen = torch.Generator(device=device)
    gen.manual_seed(args.seed)
    cols = ["group", "dist", "block", "call", "rows", "width", "k", "len_first", "len_step"]

    with open(args.out, "w", encoding="utf-8") as log:
        log.write("# torch.topk measured on the same GPU; format at the top of bench/bench_torch.py\n")
        log.write(f"# time: {time.strftime('%Y-%m-%d %H:%M:%S')}\n")
        log.write(f"# gpu: {torch.cuda.get_device_name(0)}\n")
        log.write(f"# torch: {torch.__version__}, cuda {torch.version.cuda}\n")
        if any(name.startswith("deepselect") for name, _ in impls):
            import deep_select
            log.write(f"# deep_select: {getattr(deep_select, '__version__', '?')}\n")
        if any(name == "flashinfer" for name, _ in impls):
            import flashinfer
            log.write(f"# flashinfer: {getattr(flashinfer, '__version__', '?')}, top_k_ragged_transform, "
                      f"deterministic=True, tie_break={FLASHINFER_TIE_BREAK}\n")
        if any(name in CHECKED for name, _ in impls):
            log.write("# check: group,dist,block,call,impl,rows with a wrong set,rows where a tie did not go to the smaller position,runs differing from the first,rows not in ascending position order\n")
        log.write(f"# seed: {args.seed}\n# reps: {args.reps}\n")
        log.write(",".join(cols) + ",impl,threads,rep,seconds,out_hash\n")

        totals = {}  # sum of the medians of the calls of group 1, per (dist, impl)
        bad = {}     # per checked implementation: totals of the four numbers of its # check lines
        for i, call in enumerate(plan):
            x, lens = make_scores(call, gen, device)
            k = int(call["k"])
            for name, fn in impls:
                if i == 0:  # the very first call of the program runs once unmeasured, to exclude one-time costs
                    fn(x, lens, k)
                    torch.cuda.synchronize()
                secs = []
                first = None
                ndiff = 0
                for rep in range(args.reps):
                    torch.cuda.synchronize()
                    t0 = time.perf_counter()
                    out = fn(x, lens, k)
                    torch.cuda.synchronize()
                    secs.append(time.perf_counter() - t0)
                    if name in CHECKED:
                        if first is None:
                            first = out.clone()
                        elif not torch.equal(out, first):
                            ndiff += 1
                    del out
                    log.write(",".join(call[c] for c in cols) + f",{name},0,{rep},{secs[-1]:.9f},-\n")
                if first is not None:
                    ordered, moved = ascending(first)
                    w, t = check_rule(x, lens, k, ordered)
                    log.write(f"# check: {call['group']},{call['dist']},{call['block']},{call['call']},{name},{w},{t},{ndiff},{moved}\n")
                    b = bad.setdefault(name, [0, 0, 0, 0])
                    for j, v in enumerate((w, t, ndiff, moved)):
                        b[j] += v
                    del first, ordered
                if call["group"] == "1":
                    key = (call["dist"], name)
                    totals[key] = totals.get(key, 0.0) + statistics.median(secs)
            del x, lens
            log.flush()
        log.write(f"# peak_gpu_mem_mib: {torch.cuda.max_memory_allocated() / 2**20:.0f}\n")

    if any(c["group"] == "1" for c in plan):
        for (dist, name), t in totals.items():
            print(f"group 1 total ({dist}), {name}: {t:.3f} s per layer, 61 layers take {t * 61:.1f} s")
    for name, (w, t, d, m) in bad.items():
        print(f"{name}: rows with a wrong set {w}, rows where a tie did not go to the smaller position {t}, "
              f"runs differing from the first {d}, rows not in ascending position order {m}")
    print(f"log: {args.out}")


if __name__ == "__main__":
    main()
